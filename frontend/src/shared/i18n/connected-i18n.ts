export function useConnectedText() {
  const context = useLocale();
  const i =
    context.locale === "de-DE"
      ? 1
      : context.locale === "fr-FR"
        ? 2
        : context.locale === "es-ES"
          ? 3
          : 0;
  return { ...context, x: (key: string) => connectedWords[key]?.[i] ?? key };
}
