export function useOperationsText() {
  const { locale } = useLocale();
  const i =
    ({ en: 0, de: 1, fr: 2, es: 3 } as const)[locale.slice(0, 2) as "en"] ?? 0;
  return {
    o: (key: string) =>
      operationWords[key as keyof typeof operationWords]?.[i] ?? key,
    locale,
  };
}
