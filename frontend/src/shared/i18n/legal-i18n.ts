export type LegalWord = keyof typeof legalWords;
export function useLegalText() {
  const { locale } = useLocale();
  const index =
    ({ en: 0, de: 1, fr: 2, es: 3 } as Record<string, number>)[
      locale.split("-")[0]
    ] ?? 0;
  return { locale, l: (key: LegalWord) => legalWords[key][index] };
}
