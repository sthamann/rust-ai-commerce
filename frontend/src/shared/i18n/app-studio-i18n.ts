export type AppStudioKey = keyof typeof appStudioWords;
export function useAppStudioText() {
  const context = useLocale();
  const index = context.locale.startsWith("de")
    ? 1
    : context.locale.startsWith("fr")
      ? 2
      : context.locale.startsWith("es")
        ? 3
        : 0;
  return { ...context, a: (key: AppStudioKey) => appStudioWords[key][index] };
}
export function appText(key: AppStudioKey) {
  const values = appStudioWords[key];
  return { en: values[0], de: values[1], fr: values[2], es: values[3] };
}
