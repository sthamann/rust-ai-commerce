export function useCatalogText() {
  const { locale, money } = useLocale();
  const index = ({ "en-GB": 0, "de-DE": 1, "fr-FR": 2, "es-ES": 3 } as const)[
    locale
  ];
  return { locale, money, c: (key: CatalogWord) => words[key][index] };
}
