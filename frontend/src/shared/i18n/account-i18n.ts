export type AccountKey = keyof typeof accountWords;
export function useAccountText() {
  const { locale } = useLocale();
  const index =
    ({ en: 0, de: 1, fr: 2, es: 3 } as const)[locale.slice(0, 2) as "en"] ?? 0;
  return { a: (key: AccountKey) => accountWords[key][index], locale };
}
