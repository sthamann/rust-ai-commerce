export type WorkbenchKey = keyof typeof workbenchWords;
export function useWorkbenchText() {
  const context = useLocale();
  const i =
    context.locale === "de-DE"
      ? 1
      : context.locale === "fr-FR"
        ? 2
        : context.locale === "es-ES"
          ? 3
          : 0;
  return { ...context, w: (key: WorkbenchKey) => workbenchWords[key][i] };
}
